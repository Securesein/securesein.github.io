class EpochSource:
    """One CSV inside the bundle, mapped onto one registry slug."""

    def __init__(
        self,
        filename: str,
        slug: str,
        score_column: str,
        scale: float = 1.0,
        *,
        internal: bool = True,
        variant: str = "",
        tools: bool = False,
        default_evaluator: str = "",
    ):
        self.filename = filename
        self.slug = slug
        self.score_column = score_column
        # Epoch's own `scale` factor from benchmark_metadata.csv: raw *
        # scale is the score as a 0-1 fraction.
        self.scale = scale
        self.internal = internal
        # Which cut of a benchmark this file is. FrontierMath ships four
        # incompatible private sets; a score without the set is noise.
        self.variant = variant
        self.tools = tools
        self.default_evaluator = default_evaluator or (
            EVALUATOR_EPOCH if internal else "Unattributed leaderboard"
        )


