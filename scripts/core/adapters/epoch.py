# Where a measurement date can hide, best first. `Started at` is when
# Epoch actually ran the eval; `Release date` is the *model's* release
# and only the last resort, since it says nothing about when the number
# was produced.
DATE_COLUMNS = (
    "Started at",
    "Run date",
    "Date of evaluation",
    "Date added",
    "Created",
    "Release date",
)

# Rows whose Source names the model's own lab are vendor claims, not
# independent measurements, whatever file they arrive in.
