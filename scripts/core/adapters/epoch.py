def download_bundle(force: bool = False) -> Path:
    """Fetch (and cache) the CC-BY bundle. Kept separate from parsing so
    a run can be replayed offline against the cached zip."""
    import requests

    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    fresh = (
        CACHE_FILE.exists()
        and (time.time() - CACHE_FILE.stat().st_mtime) < CACHE_TTL_SECONDS
    )
    if fresh and not force:
        return CACHE_FILE

    response = requests.get(
        EPOCH_BULK_ZIP_URL,
        timeout=FETCH_TIMEOUT * 3,
        headers={"User-Agent": USER_AGENT},
    )
    response.raise_for_status()
    CACHE_FILE.write_bytes(response.content)
    return CACHE_FILE


def best_date(row: dict) -> str:
    """ISO date (YYYY-MM-DD) for when this number was produced."""
    for column in DATE_COLUMNS:
        value = (row.get(column) or "").strip()
        if value:
            return value[:10]
    return ""


def _float(value: str) -> float | None:
    try:
        return float(str(value).strip())
    except (TypeError, ValueError):
        return None


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-")


def _conditions(source: EpochSource, row: dict, effort: str | None) -> dict:
    """Never empty. A score with no conditions is a number, not a
    finding (brief §4), so every record carries at least a sentence
    about how it was produced."""
    notes: list[str] = []
    if source.variant:
        notes.append(source.variant)
    for column, label in (
        ("Agent", "agent"),
        ("LiveBench Version", "question set"),
        ("Edit format", "edit format"),
        ("Notes", "note"),
        ("Notes (details)", "note"),
    ):
        value = (row.get(column) or "").strip()
        if value:
            notes.append(f"{label}: {value}")
    for column in ("stderr", "Accuracy SE", "Accuracy Standard Error"):
        value = _float(row.get(column, ""))
        if value is not None:
            notes.append(f"stderr {value:.3g}")
            break

    conditions: dict = {"tools": source.tools}
    if effort:
        conditions["reasoningEffort"] = effort
    if source.internal:
        # Epoch documents these for every internal run.
        conditions["shots"] = 0
        notes.append(
            "Epoch AI house conditions: zero-shot chain-of-thought, empty system "
            "prompt, API-default temperature, chat/instruct variant"
        )
    conditions["notes"] = "; ".join(notes) if notes else (
        f"Redistributed by Epoch AI from {source.default_evaluator}; "
        "run conditions not published per-row"
    )
    return conditions


def _evaluator_and_kind(source: EpochSource, row: dict) -> tuple[str, str]:
    """(evaluator, measuredBy) for one row."""
    if source.internal:
        return EVALUATOR_EPOCH, "thirdparty"

    raw = (row.get("Source") or "").strip()
    if not raw:
        return source.default_evaluator, "community"
    if raw.startswith("http"):
        return source.default_evaluator, "community"

    lowered = raw.lower()
    organisation = (row.get("Organization") or "").split(",")[0].strip()
    if organisation and organisation.split()[0].lower() in lowered:
        # The Source cell describes where the number came from
        # ("Anthropic annoucement" — Epoch's own typo); the evaluator
        # field wants the party that produced it. Strip the descriptor
        # and keep the organisation's own spelling of its name.
        return organisation, "vendor"
    return raw, "community"


def _source_url(source: EpochSource, row: dict) -> str:
    for column in ("Source link", "Source Link", "Log viewer", "Logs"):
        value = (row.get(column) or "").strip()
        if value.startswith("http"):
            return value
    raw = (row.get("Source") or "").strip()
    if raw.startswith("http"):
        return raw
    return HUB_URL


def measurement_id(slug: str, model_id: str, evaluator: str, measured_at: str) -> str:
    """`<benchmark>--<model>--<evaluator>--<YYYY-MM-DD>`, per §4."""
    return f"{slug}--{model_id}--{_slug(evaluator)}--{measured_at}"


def read_rows(bundle_path: Path | None = None) -> list[tuple[EpochSource, dict]]:
    """Every in-scope row in the bundle, unresolved and unnormalised."""
    path = bundle_path or download_bundle()
    rows: list[tuple[EpochSource, dict]] = []
    with zipfile.ZipFile(path) as bundle:
        available = set(bundle.namelist())
        for source in EPOCH_SOURCES:
            if source.filename not in available:
                print(
                    f"    epoch: {source.filename} missing from the bundle — skipped",
                    file=sys.stderr,
                )
                continue
            text = bundle.read(source.filename).decode("utf-8")
            for row in csv.DictReader(io.StringIO(text)):
                rows.append((source, row))
    return rows


def collect(
    registry,
    bundle_path: Path | None = None,
    *,
    since: str = EPOCH_BACKFILL_START,
) -> tuple[list[dict], list[dict]]:
    """Normalise the bundle into collection-shaped measurement records.

    Returns (measurements, unresolved). Unresolved entries are model
    names the registry could not place; they are parked by the caller
    and never invented into the collection.
    """
    measurements: list[dict] = []
    unresolved: list[dict] = []
    seen_unresolved: set[str] = set()

    from ..registry import effort_of

    for source, row in read_rows(bundle_path):
        benchmark = registry.resolve_benchmark(source.slug)
        if benchmark is None:
            continue  # slug not in the closed vocabulary: drop, never invent

        measured_at = best_date(row)
        if not measured_at or measured_at < since:
            continue

        raw_score = _float(row.get(source.score_column, ""))
        if raw_score is None:
            continue

        version = (row.get("Model version") or "").strip()
        if not version:
            continue

        model = registry.resolve_model(version)
        if model is None:
            if version not in seen_unresolved:
                seen_unresolved.add(version)
                unresolved.append(
                    {
                        "name": version,
                        "source": "epoch",
                        "benchmark": source.slug,
                        "organization": (row.get("Organization") or "").strip(),
                        "seenAt": measured_at,
                    }
                )
            continue

        fraction = raw_score * source.scale
        if benchmark.unit == "percent":
            value = round(fraction * 100, 2)
        else:
            # Elo and 0-100 composite scores are already in their own
            # unit; scaling them would be a silent unit error.
            value = round(raw_score, 3)

        effort = effort_of(version)
        evaluator, measured_by = _evaluator_and_kind(source, row)

        measurements.append(
            {
                "id": measurement_id(benchmark.slug, model.id, evaluator, measured_at),
                "model": model.id,
                "vendor": model.vendor,
                "benchmark": benchmark.slug,
                "metric": benchmark.metric,
                "value": value,
                "unit": benchmark.unit,
                "measuredBy": measured_by,
                "evaluator": evaluator,
                "harness": "inspect" if source.internal else None,
                "conditions": _conditions(source, row, effort),
                "measuredAt": measured_at,
                "sourceUrl": _source_url(source, row),
                "publisher": PUBLISHER,
                "license": EPOCH_LICENSE,
                "attribution": EPOCH_ATTRIBUTION,
            }
        )

    return measurements, unresolved
