"""
Epoch AI Benchmarking Hub adapter — the spine of the benchmarks
channel, and per brief §7.1 the one adapter that had to be built first
and completely.

Two ways in, in the brief's own order of preference:

  1. the published client library (`pip install epochai`), which reads
     the same records through Epoch's Airtable API;
  2. the bulk CC-BY data bundle at epoch.ai/data/benchmark_data.zip,
     which is the documented fallback and contains exactly the same
     CSVs the hub renders.

The bundle is tried second and is what runs in CI, because it needs no
extra dependency and no API round-trips; the client library is used
when it happens to be installed, which keeps the brief's stated
preference honest without making `epochai` a hard requirement of the
whole pipeline.

Two things this adapter is careful about, because they are the reason
the channel exists at all:

**Conditions travel with the number.** Epoch documents its own run
conditions (chat/instruct variants, API-default temperature, zero-shot
chain-of-thought, empty system prompt) and records a reasoning-effort
suffix on the model version. All of that is written into
`conditions`; a record is never emitted with an empty one.

**Epoch's own runs and Epoch's redistribution of someone else's runs
are not the same evidence.** Files without an `_external` suffix are
Epoch's internal evaluations (`measuredBy: thirdparty`, evaluator
"Epoch AI", harness `inspect`). Files with it are numbers Epoch
collected from a leaderboard or a vendor announcement, and the
evaluator is taken from the row's own `Source` column — including the
handful of rows whose source is a vendor's own announcement, which are
correctly recorded as `measuredBy: vendor` and are exactly the material
the vendor-versus-third-party gap trigger feeds on.
"""

